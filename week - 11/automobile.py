import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df=pd.read_csv("/content/Automobile_data.csv")

print("First 5 Records:")
display(df.head())

print("Last 5 Records:")
display(df.tail())

print("Dataset Shape:", df.shape)
print("Columns:", df.columns.tolist())

print("\nDataset Information:")
df.info()

print("\nStatistical Summary:")
display(df.describe())

df.replace('?', np.nan, inplace=True)

print("\nMissing Values:")
print(df.isnull().sum())



cols = ['horsepower', 'peak-rpm', 'bore', 'stroke', 'price']

for col in cols:
    df[col] = pd.to_numeric(df[col], errors='coerce')
    df[col] = df[col].fillna(
        df.groupby('make')[col].transform('median')
    )
    df[col] = df[col].fillna(df[col].median())

print("\nMissing Values After Cleaning:")
print(df[cols].isnull().sum())

df['horsepower'] = df['horsepower'].round().astype(int)
df['peak-rpm'] = df['peak-rpm'].astype(float)
df['price'] = df['price'].astype(float)
df['bore'] = df['bore'].astype(float)
df['stroke'] = df['stroke'].astype(float)

print("\nUpdated Data Types:")
df.info()

df['power_to_weight_ratio'] = (
    df['horsepower'] / df['curb-weight']
) * 1000

print("\nPower-to-Weight Ratio:")
display(df[['make', 'horsepower', 'curb-weight',
            'power_to_weight_ratio']].head())

df['combined_mpg'] = (
    df['city-mpg'] + df['highway-mpg']
) / 2

print("\nCombined MPG:")
display(df[['make', 'city-mpg', 'highway-mpg',
            'combined_mpg']].head())

print("\nBody Style Analysis:")

body_stats = df.groupby('body-style').agg({
    'horsepower': 'mean',
    'engine-size': 'mean',
    'curb-weight': 'mean',
    'price': 'mean',
    'combined_mpg': 'mean'
})

display(body_stats)

print("\nEngine Location Analysis:")

engine_stats = df.groupby('engine-location').agg({
    'horsepower': 'mean',
    'engine-size': 'mean',
    'curb-weight': 'mean',
    'price': 'mean'
})

display(engine_stats)

print("\nRemaining Missing Values:")
print(df.isnull().sum())

print("\nDuplicate Records:", df.duplicated().sum())

print("\nFinal Dataset:")
display(df.head())

df.to_csv('automobile_cleaned.csv', index=False)

print("\nDataset successfully saved as automobile_cleaned.csv")